#!/usr/bin/env bash
# Regenerate tests/vectors/lazer_anon_cred_pp_v0.txt from LaZer's OWN C code.
#
#   LAZER=<LaZer checkout at 10eafeca4cd53ff4fc54193dce904dbd0026fefd>
#   GMP_INC/GMP_LIB, MPFR_INC/MPFR_LIB: GMP 6.3 and MPFR 4.2 headers and libraries
#   ./gen_anon_cred_pp_kat.sh > ../vectors/lazer_anon_cred_pp_v0.txt
#
# Links LaZer's unmodified src/lazer.c (unity build) with hexl_stub.c, whose NTT entry points
# abort if reached: uniform sampling never touches the NTT, so a vector produced here cannot
# have gone through the stubs. Builds both TARGET_AMD64 (AES-NI) and TARGET_GENERIC and refuses
# to emit anything unless the two outputs are byte-identical.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
: "${LAZER:?}" "${GMP_INC:?}" "${GMP_LIB:?}" "${MPFR_INC:?}" "${MPFR_LIB:?}"
[ "$(git -C "$LAZER" rev-parse HEAD)" = 10eafeca4cd53ff4fc54193dce904dbd0026fefd ] || { echo "LaZer is not at 10eafeca" >&2; exit 1; }
work=$(mktemp -d); trap 'rm -rf "$work"' EXIT
F="$LAZER/third_party/Falcon-impl-20211101"
if [ ! -d "$F" ]; then
  (cd "$LAZER/third_party" && python3 -I -c "import zipfile;zipfile.ZipFile('Falcon-impl-20211101.zip').extractall('.')")
  patch -s -d "$F" -p1 < "$LAZER/src/falcon.patch"
fi
for t in AMD64 GENERIC; do
  mkdir -p "$work/$t"
  sed "s/#define TARGET TARGET_AMD64/#define TARGET TARGET_$t/" "$LAZER/config.h" > "$work/$t/config.h"
  # lazer.h is generated by LaZer's Makefile rule `lazer.h:` from lazer-in1.h, config.h, lazer-in2.h
  (cd "$LAZER" && cp config.h "$work/config.orig" && cp "$work/$t/config.h" config.h \
     && rm -f lazer.h && make -s lazer.h && mv lazer.h "$work/$t/lazer.h"; cp "$work/config.orig" config.h)
  gcc -O1 -w -maes -mavx2 -mfma -mpclmul -mssse3 -I"$work/$t" -I"$LAZER" -I"$LAZER/src" -I"$F" \
      -I"$GMP_INC" -I"$MPFR_INC" -o "$work/pp_$t" "$here/pp_kat.c" "$LAZER/src/lazer.c" \
      "$here/hexl_stub.c" $(ls "$F"/*.c | grep -v -E 'test_falcon|speed') \
      -L"$MPFR_LIB" -lmpfr -L"$GMP_LIB" -lgmp -lm
done
seed=$(python3 -I -c "import hashlib;print(hashlib.shake_128(b'\x00').digest(32).hex())")
"$work/pp_AMD64" "$seed" > "$work/a.txt"
"$work/pp_GENERIC" "$seed" > "$work/g.txt"
cmp "$work/a.txt" "$work/g.txt" >&2
python3 -I "$here/format_kat.py" "$seed" "$work/a.txt"
