//! C harness generation. One harness per target; modes selected by argv[1]:
//! `kat` prints the output buffers as hex, `taint` marks secrets undefined with Valgrind client
//! requests and calls the function, `time N` prints N `class nanoseconds` lines for dudect.

use std::fmt::Write;

use crate::config::{ArgKind, Ret, Target};

pub fn generate(t: &Target) -> String {
    let mut s = String::new();
    s.push_str(PRELUDE);
    // Prototype (declared in this translation unit only; pointers are passed as unsigned char*).
    let proto: Vec<String> = t
        .args
        .iter()
        .map(|a| {
            if a.kind == ArgKind::Len {
                "size_t".to_string()
            } else {
                "unsigned char *".to_string()
            }
        })
        .collect();
    let ret = if t.ret == Ret::Int { "int" } else { "void" };
    let _ = writeln!(s, "extern {ret} {}({});", t.function, proto.join(", "));
    for (i, a) in t.args.iter().enumerate() {
        if a.kind != ArgKind::Len {
            let _ = writeln!(s, "static unsigned char b{i}[{}];", a.len);
        }
    }
    s.push_str("static void init_public(void) {\n");
    for (i, a) in t.args.iter().enumerate() {
        if a.kind == ArgKind::Public {
            let _ = writeln!(s, "  fill(b{i}, {});", a.len);
        }
    }
    s.push_str("}\nstatic void fill_secrets(int cls) {\n  (void)cls;\n");
    for (i, a) in t.args.iter().enumerate() {
        if a.kind == ArgKind::Secret {
            let _ = writeln!(
                s,
                "  if (cls == 0) memset(b{i}, 0, {0}); else fill(b{i}, {0});",
                a.len
            );
        }
    }
    s.push_str("}\nstatic void call(void) {\n  ");
    let call_args: Vec<String> = t
        .args
        .iter()
        .enumerate()
        .map(|(i, a)| match a.kind {
            ArgKind::Len => format!("(size_t){}", t.args[a.of.unwrap_or(0)].len),
            _ => format!("b{i}"),
        })
        .collect();
    let _ = writeln!(
        s,
        "{}{}({});\n  {}\n}}",
        if t.ret == Ret::Int {
            "volatile int r = "
        } else {
            ""
        },
        t.function,
        call_args.join(", "),
        if t.ret == Ret::Int { "(void)r;" } else { "" }
    );
    s.push_str("static void print_outs(void) {\n  printf(\"OUT \");\n");
    for (i, a) in t.args.iter().enumerate() {
        if a.kind == ArgKind::Out {
            let _ = writeln!(s, "  hex(b{i}, {});", a.len);
        }
    }
    s.push_str("  printf(\"\\n\");\n}\n");
    s.push_str("#ifdef CTKAT_VG\nstatic void taint(void) {\n");
    for (i, a) in t.args.iter().enumerate() {
        if a.kind == ArgKind::Secret {
            let _ = writeln!(s, "  VALGRIND_MAKE_MEM_UNDEFINED(b{i}, {});", a.len);
        }
    }
    s.push_str("}\nstatic void declassify_outs(void) {\n");
    for (i, a) in t.args.iter().enumerate() {
        if a.kind == ArgKind::Out {
            let _ = writeln!(s, "  VALGRIND_MAKE_MEM_DEFINED(b{i}, {});", a.len);
        }
    }
    s.push_str("}\n#endif\n");
    s.push_str(MAIN);
    s
}

const PRELUDE: &str = r#"/* generated by cargo ct-kat; do not edit */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#if defined(__has_include)
# if __has_include(<valgrind/memcheck.h>)
#  include <valgrind/memcheck.h>
#  define CTKAT_VG 1
# endif
#endif
static uint64_t st = 0x9E3779B97F4A7C15ull;
static uint64_t nx(void) { st ^= st << 13; st ^= st >> 7; st ^= st << 17; return st; }
static void fill(unsigned char *p, size_t n) { for (size_t i = 0; i < n; i++) p[i] = (unsigned char)nx(); }
static void hex(const unsigned char *p, size_t n) { for (size_t i = 0; i < n; i++) printf("%02x", p[i]); }
"#;

const MAIN: &str = r#"
int main(int argc, char **argv) {
  const char *m = argc > 1 ? argv[1] : "kat";
  init_public();
  if (!strcmp(m, "kat")) { fill_secrets(1); call(); print_outs(); return 0; }
  if (!strcmp(m, "taint")) {
#ifdef CTKAT_VG
    fill_secrets(1); taint(); call(); declassify_outs(); return 0;
#else
    return 77; /* no Valgrind client-request header at build time */
#endif
  }
  if (!strcmp(m, "time")) {
    long n = argc > 2 ? atol(argv[2]) : 10000;
    if (n < 2) return 2;
    int *cl = malloc((size_t)n * sizeof *cl);
    uint64_t *ns = malloc((size_t)n * sizeof *ns);
    if (!cl || !ns) return 3;
    for (long i = 0; i < n; i++) {
      int c = (int)(nx() & 1);
      fill_secrets(c);
      struct timespec a, b;
      clock_gettime(CLOCK_MONOTONIC, &a);
      call();
      clock_gettime(CLOCK_MONOTONIC, &b);
      cl[i] = c;
      ns[i] = (uint64_t)(b.tv_sec - a.tv_sec) * 1000000000ull + (uint64_t)(b.tv_nsec - a.tv_nsec);
    }
    for (long i = 0; i < n; i++) printf("%d %llu\n", cl[i], (unsigned long long)ns[i]);
    return 0;
  }
  return 2;
}
"#;
